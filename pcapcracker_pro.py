class L:
    G  = '\033[38;5;22m'
    LG = '\033[38;5;46m'
    RS = Style.RESET_ALL

    @staticmethod
    def _raw(s):
        return re.sub(r'\x1b\[[0-9;]*m', '', s)

    @staticmethod
    def box(title, lines):
        rw = max(len(L._raw(title)), max(len(L._raw(l)) for l in lines)) + 4
        bar = '─' * rw
        print(f"\n{L.G}┌{bar}┐{L.RS}")
        pad = rw - len(L._raw(title)) - 2
        print(f"{L.G}│{L.RS}{' '*(pad//2)}{title}{' '*(pad-pad//2)}{L.G}│{L.RS}")
        print(f"{L.G}├{bar}┤{L.RS}")
        for line in lines:
            rpad = rw - len(L._raw(line)) - 1
            print(f"{L.G}│{L.RS} {line}{' '*rpad}{L.G}│{L.RS}")
        print(f"{L.G}└{bar}┘{L.RS}\n")

    @staticmethod
    def success_box(ssid, bssid, pwd):
        play_sound()
        lines = [
            f"  {L.G}SSID     {L.RS}:: {L.LG}{ssid}{L.RS}",
            f"  {L.G}BSSID    {L.RS}:: \033[96m{bssid}\033[0m",
            f"  {L.G}PASSWORD {L.RS}:: {L.LG}{pwd}{L.RS}",
        ]
        L.box(f"{L.LG}ACCESS_GRANTED // PASSWORD CRACKED{L.RS}", lines)

    @staticmethod
    def i(m):  print(f"  {L.G}[*]{L.RS} {m}")
    @staticmethod
    def s(m):  print(f"  {L.LG}[+]{L.RS} {m}")
    @staticmethod
    def w(m):  print(f"  \033[33m[!]\033[0m {m}")
    @staticmethod
    def e(m):  print(f"  \033[31m[✗]\033[0m {m}")
    @staticmethod
    def p(m):  print(f"  {L.G}[~]{L.RS} {m}")
    @staticmethod
    def sect(title):
        bar = '─' * 52
        print(f"\n{L.G}{bar}{L.RS}")
        print(f"{L.G}  // {L.LG}{title.upper()}{L.RS}")
        print(f"{L.G}{bar}{L.RS}\n")


