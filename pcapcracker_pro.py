    def auto_extract(self):
        G  = '\033[38;5;22m'; LG = '\033[38;5;46m'; RS = Style.RESET_ALL
        bar = f"{G}  {'─'*50}{RS}"
        print(f"\n{bar}")
        print(f"{G}  // {LG}SCANNING PCAP DIRECTORY{RS}")
        print(f"{bar}")
        if not os.path.exists(cfg.PCAP): os.makedirs(cfg.PCAP)
        pcaps = [f for f in os.listdir(cfg.PCAP)
                 if f.lower().endswith(('.pcap', '.pcapng', '.cap', '.scap'))]
        if not pcaps:
            L.w("no pcap files found in pcap/")
        else:
            L.i(f"{len(pcaps)} file(s) detected — starting hash extraction")
            for p in tqdm(pcaps, desc="  extracting", unit="pcap",
                          bar_format="  {l_bar}{bar}| {n_fmt}/{total_fmt} [{elapsed}]"):
                Ext.extract(f"{cfg.PCAP}/{p}")
        self.ssid_map = build_ssid_map()
        if self.ssid_map:
            print(f"\n{bar}")
            print(f"{G}  // {LG}TARGETS IDENTIFIED{RS}")
            print(f"{bar}")
            for ssid, paths in self.ssid_map.items():
                n = len(paths)
                print(f"  {G}[+]{RS} {LG}{ssid}{RS}  {G}// {n} hash{'es' if n>1 else ''}{RS}")
            print(f"{bar}")
        else:
            L.w("no hashes available after extraction")
        print()

